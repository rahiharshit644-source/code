package com.example.domain.agent

import com.example.core.model.*
import com.example.core.network.OmniRouteClient
import com.example.core.storage.ProjectFileManager
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.flow.collect
import java.util.UUID

class CodingAgentEngine(
    private val omniRouteClient: OmniRouteClient,
    private val fileManager: ProjectFileManager,
    private val contextIndexer: ProjectContextIndexer
) {

    data class AgentPlanResult(
        val planSteps: List<String>,
        val changeSet: ProposedChangeSet?,
        val finalMessage: String
    )

    fun executeCodingTask(
        projectId: String,
        userPrompt: String,
        config: OmniRouteConfig,
        taskHistory: List<ChatMessage> = emptyList()
    ): Flow<String> = flow {
        // 1. Context retrieval
        emit("🔍 Inspecting project architecture and indexing repository files...\n")
        val contextBundle = contextIndexer.buildContext(
            projectId = projectId,
            userPrompt = userPrompt,
            maxCharBudget = config.contextBudgetTokens * 3
        )
        emit("📊 Indexed ${contextBundle.totalFileCount} files (~${contextBundle.estimatedTokens} tokens of context).\n\n")

        // 2. Build system prompt
        val systemPrompt = buildSystemPrompt(contextBundle)

        val messages = mutableListOf<Pair<String, String>>()
        messages.add("system" to systemPrompt)

        // Include recent conversation turns for context
        for (hist in taskHistory.takeLast(4)) {
            val role = when (hist.sender) {
                MessageSender.USER -> "user"
                MessageSender.AGENT -> "assistant"
                MessageSender.SYSTEM -> "system"
            }
            messages.add(role to hist.text)
        }
        messages.add("user" to userPrompt)

        emit("🧠 Formulating implementation plan with OmniRoute (${config.selectedModel})...\n\n")

        // Do not fabricate code changes when the gateway is unavailable. Let the caller
        // surface the real network/provider error and preserve the project unchanged.
        omniRouteClient.streamChatCompletion(config, messages).collect { chunk ->
            emit(chunk)
        }
    }

    private fun buildSystemPrompt(contextBundle: ProjectContextIndexer.ContextBundle): String {
        val filesText = contextBundle.keyFilesContent.entries.joinToString("\n\n") { (path, content) ->
            "--- FILE: $path ---\n$content\n--- END FILE ---"
        }

        return """
You are CodePilot AI, a principal native Android & cross-platform coding agent connected via OmniRoute.
You specialize in real repository modifications, bug fixing, refactoring, test generation, and architectural reviews.
You understand English, Hindi, and Hinglish instructions natively.

PROJECT REPOSITORY CONTEXT:
File Tree:
${contextBundle.fileTreeSummary}

Key Relevant Files:
$filesText

WORKFLOW INSTRUCTIONS:
1. Always start with a concise 3-4 bullet IMPLEMENTATION PLAN.
2. If language requested is Hindi or Hinglish, explain your thoughts in that language while keeping code syntax standard.
3. For EVERY file you need to create, modify, rename, or delete, output your changes in this precise structured format:
<file_change path="relative/path/to/file" type="create|modify|delete" reason="Brief explanation">
Full updated or new content for the file here...
</file_change>
4. Ensure files are clean, compilable, and complete (no placeholders like 'TODO: implement the rest').
5. For renames, provide both path="new/path" and old_path="existing/path" attributes.
6. Never claim a build or test passed unless it was actually executed.
7. Summarize completed actions at the end.
        """.trimIndent()
    }

    fun parseOutputToChangeSet(
        taskId: String,
        projectId: String,
        title: String,
        modelOutput: String
    ): ProposedChangeSet {
        val diffItems = DiffEngine.parseModelChanges(modelOutput) { relPath ->
            try {
                fileManager.readFileContent(projectId, relPath)
            } catch (e: Exception) {
                ""
            }
        }

        return ProposedChangeSet(
            id = UUID.randomUUID().toString(),
            taskId = taskId,
            title = title,
            explanation = "Changes generated by CodePilot AI based on requirements.",
            files = diffItems
        )
    }

}
